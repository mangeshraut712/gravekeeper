/**
 * Revival kit: REVIVAL.md and a "Revival tracking issue" body, generated from a
 * lookup that has already passed verifyProof().
 *
 * Pure and isomorphic: no network, no environment reads, no clock or locale reads,
 * so the same input always gives the same bytes. Every user-controlled string goes
 * through escapeMarkdown() exactly once and never starts a line.
 */

import type {
  AutopsyDependency,
  DependencyAutopsy,
  EpitaphTimeline,
  ResurrectResponse,
} from "@/types";
import { timestampToIso } from "../wayback/timeline.ts";

export const KIT_FILENAME = "REVIVAL.md";
export const PROOF_FILENAME = "gravekeeper-proof.json";
export const MAX_COMMITS = 5;

export type RevivalKitInput = {
  result: ResurrectResponse; // already verified
  resource: string; // normalized resource URL (receipts[0].url)
  proofSha256: string; // SHA-256 hex of the exported proof file bytes
};

// C0/C1 controls (CR, LF, TAB…), line/paragraph separators, bidi marks and overrides.
const LAYOUT =
  /[\u0000-\u001f\u007f-\u009f\u2028\u2029\u200e\u200f\u202a-\u202e\u2066-\u2069]+/g;
const SPECIAL = /[&<>\\`*_[\]()#!|~@$]/g;
const ENTITY: Record<string, string> = { "&": "&amp;", "<": "&lt;", ">": "&gt;" };

/**
 * Neutralize a user-controlled string for inline Markdown: no HTML, links, images,
 * code, emphasis, table breaks, mentions, issue references, math or new blocks.
 */
export function escapeMarkdown(value: unknown, max = 500): string {
  let text = String(value ?? "").replace(LAYOUT, " ").trim();
  const points = Array.from(text);
  if (points.length > max) text = points.slice(0, max).join("").trimEnd() + "…";
  return text.replace(SPECIAL, (char) => ENTITY[char] ?? `\\${char}`);
}

const HEX = /^[0-9a-f]+$/;
const B64URL = /^[A-Za-z0-9_-]+$/;

/** Code span only for values that cannot contain Markdown; otherwise escaped text. */
function code(value: string, pattern: RegExp): string {
  return pattern.test(value) ? `\`${value}\`` : escapeMarkdown(value);
}

/** Same rule as safeSnapshotUrl: https, web.archive.org only, no credentials or port. */
function snapshotHref(value: string | null | undefined): string | null {
  if (!value) return null;
  try {
    const url = new URL(value);
    if (
      !["https:", "http:"].includes(url.protocol) ||
      url.hostname !== "web.archive.org" ||
      url.username ||
      url.password ||
      url.port
    )
      return null;
    url.protocol = "https:";
    const encoded: Record<string, string> = { "(": "%28", ")": "%29", " ": "%20" };
    return url.href.replace(/[() ]/g, (char) => encoded[char]);
  } catch {
    return null;
  }
}

function waybackDate(timestamp: string | null | undefined): string | null {
  return timestamp ? timestampToIso(timestamp) : null;
}

function snapshotLine(result: ResurrectResponse): string {
  const href = snapshotHref(result.wayback?.snapshotUrl);
  if (!href) return "None found";
  const when = waybackDate(result.wayback?.timestamp);
  return `[Wayback Machine capture${when ? ` of ${when}` : ""}](${href})`;
}

function repoLink(result: ResurrectResponse): string {
  const meta = result.github!.meta;
  const href = `https://github.com/${encodeURIComponent(meta.owner)}/${encodeURIComponent(meta.repo)}`;
  return `[${escapeMarkdown(meta.fullName)}](${href})`;
}

function num(value: unknown): string {
  return typeof value === "number" && Number.isFinite(value) ? String(value) : "Unknown";
}

function recordedAt(result: ResurrectResponse): string {
  return escapeMarkdown(result.receipts[0]?.fetchedAt ?? "unknown time");
}

const TRUST =
  "Integrity only: a valid proof shows these receipts are internally consistent under the key in the file. It does not prove authorship, that GitHub, the package registries or the Internet Archive were truthful, or that later receipts were not removed.";

/** The ready-to-paste "Revival tracking issue" body. Also embedded verbatim in REVIVAL.md. */
export function buildIssueBody({ result, proofSha256 }: RevivalKitInput): string {
  const meta = result.github?.meta;
  const steps = result.spec?.revivalSteps ?? [];
  const lines = [
    "### Revival tracking issue",
    "",
    `Tracking the revival of ${meta ? escapeMarkdown(meta.fullName) : "this project"}. Plan generated by Gravekeeper from a verified lookup recorded at ${recordedAt(result)}.`,
    "",
    "#### Tasks",
    "",
    ...(steps.length
      ? steps.map(
          (step, index) =>
            `- [ ] ${index + 1}. ${escapeMarkdown(step.title)}: ${escapeMarkdown(step.description, 1000)}`,
        )
      : ["No revival plan steps were generated."]),
    "",
    "#### Evidence",
    "",
    `- Archive snapshot: ${snapshotLine(result)}`,
    `- Proof file: \`${PROOF_FILENAME}\`, SHA-256 ${code(proofSha256, HEX)}`,
    `- ${TRUST}`,
  ];
  return lines.join("\n") + "\n";
}

function factsSection(result: ResurrectResponse): string[] {
  const meta = result.github!.meta;
  const rows: [string, string][] = [
    ["Repository", repoLink(result)],
    ["Description", meta.description ? escapeMarkdown(meta.description) : "None"],
    ["Last push", escapeMarkdown(meta.pushedAt)],
    ["Stars", num(meta.stars)],
    ["Forks", num(meta.forks)],
    ["Open issues / PRs", num(meta.openIssues)],
    ["License", meta.license ? escapeMarkdown(meta.license) : "Not detected"],
    ["Default branch", escapeMarkdown(meta.defaultBranch)],
    ["Archived on GitHub", meta.archivedByGitHub ? "Yes" : "No"],
  ];
  return [
    "## Repository facts",
    "",
    "| Fact | Value |",
    "| --- | --- |",
    ...rows.map(([label, value]) => `| ${label} | ${value} |`),
  ];
}

function commitsSection(result: ResurrectResponse): string[] {
  const commits = result.github?.commits ?? [];
  const recent = commits.slice(0, MAX_COMMITS);
  return [
    "## Recent commits",
    "",
    ...(recent.length
      ? recent.map(
          (commit) =>
            `- ${code(String(commit.sha).slice(0, 7), HEX)} ${escapeMarkdown(commit.authorDate)}, ${escapeMarkdown(commit.authorName, 100)}: ${escapeMarkdown(commit.message, 200)}`,
        )
      : ["No commits were returned."]),
    ...(commits.length > recent.length
      ? ["", `Showing ${recent.length} of ${commits.length} commits in the lookup.`]
      : []),
  ];
}

function planSection(result: ResurrectResponse): string[] {
  const spec = result.spec;
  if (!spec) return ["## Revival plan", "", "No revival plan was generated for this lookup."];
  const languages = spec.detectedLanguages.map((value) => escapeMarkdown(value)).join(", ");
  return [
    "## Revival plan",
    "",
    `Detected languages: ${languages || "none reported"}.${spec.detectedFramework ? ` Framework: ${escapeMarkdown(spec.detectedFramework)}.` : ""}`,
    "",
    ...spec.revivalSteps.map(
      (step, index) =>
        `${index + 1}. **${escapeMarkdown(step.title)}.** ${escapeMarkdown(step.description, 1000)}`,
    ),
  ];
}

const STATUS_LABEL: Record<AutopsyDependency["status"], string> = {
  "major-behind": "Major behind",
  "minor-behind": "Minor behind",
  current: "Current",
  unknown: "Unknown",
  "not-found": "Not found",
};

function autopsySection(autopsy: DependencyAutopsy): string[] {
  const manifest = autopsy.manifest;
  const notes: string[] = [];
  if (autopsy.state === "no-manifest")
    notes.push("No package.json, requirements.txt or pyproject.toml at the repository root.");
  if (autopsy.state === "unavailable") notes.push("The root manifest could not be read.");
  if (autopsy.state === "partial")
    notes.push("Partial result: some registry lookups failed. Those rows are marked Unknown.");
  if (manifest?.truncated)
    notes.push(
      `Showing the first ${autopsy.dependencies.length} of ${num(manifest.totalDeclared)} declared packages.`,
    );
  if (manifest && manifest.skippedLines > 0)
    notes.push(`${num(manifest.skippedLines)} manifest entries could not be parsed and were skipped.`);
  const lines = [
    "## Dependency autopsy",
    "",
    manifest
      ? `Declared versions in ${escapeMarkdown(manifest.path)} compared with the latest ${manifest.ecosystem === "pypi" ? "PyPI" : "npm"} release. Declared versions only: no lockfile, no install, not a vulnerability scan.`
      : "Declared versions only: no lockfile, no install, not a vulnerability scan.",
    ...notes.map((note) => `- ${note}`),
  ];
  if (autopsy.dependencies.length) {
    lines.push(
      "",
      "| Package | Group | Declared | Latest | Status | Note |",
      "| --- | --- | --- | --- | --- | --- |",
      ...autopsy.dependencies.map(
        (dep) =>
          `| ${escapeMarkdown(dep.name, 214)} | ${escapeMarkdown(dep.group)} | ${dep.spec ? escapeMarkdown(dep.spec, 256) : "(unpinned)"} | ${dep.latest ? escapeMarkdown(dep.latest, 100) : "Unknown"} | ${STATUS_LABEL[dep.status] ?? "Unknown"} | ${dep.note ? escapeMarkdown(dep.note) : ""} |`,
      ),
    );
  }
  return lines;
}

function timelineSection(timeline: EpitaphTimeline): string[] {
  const head = ["## Epitaph timeline", ""];
  if (timeline.state === "unavailable")
    return [
      ...head,
      `The Internet Archive capture index could not be read (${escapeMarkdown(timeline.code ?? "unknown error")}).`,
    ];
  if (timeline.state === "empty")
    return [...head, "No captures of this exact URL were found in the Internet Archive index."];
  const born = waybackDate(timeline.firstCapture);
  const last = waybackDate(timeline.lastSeen);
  return [
    ...head,
    `- Born (first capture): ${born ? born.slice(0, 10) : "Unknown"}`,
    `- Last seen (latest captured month): ${last ? last.slice(0, 7) : "Unknown"}`,
    `- Years on record: ${num(timeline.yearsOnRecord)} (${num(timeline.yearsWithCaptures)} with captures)`,
    `- Captured months: ${num(timeline.capturedMonths)}`,
    ...(timeline.state === "truncated"
      ? ["- The index hit Gravekeeper's row limit, so later captures may be missing."]
      : []),
    "",
    "| Year | Months with a capture |",
    "| --- | --- |",
    ...timeline.years.map((entry) => `| ${num(entry.year)} | ${num(entry.months)} |`),
  ];
}

function proofSection({ result, proofSha256 }: RevivalKitInput): string[] {
  const last = result.receipts[result.receipts.length - 1];
  return [
    "## Proof reference",
    "",
    `This plan was generated from a lookup whose proof verified in the browser. Download the proof with "Download proof" on the same results page and keep it next to this file.`,
    "",
    `- Proof file: \`${PROOF_FILENAME}\``,
    `- Proof SHA-256: ${code(proofSha256, HEX)}`,
    `- Receipts: ${result.receipts.length}`,
    `- Last receipt hash: ${last ? code(last.hash, HEX) : "None"}`,
    `- Public key (Ed25519, base64url): ${code(result.publicKey, B64URL)}`,
    "",
    "Check that the proof file is the one this plan refers to, then verify it offline from a Gravekeeper checkout:",
    "",
    "```sh",
    `shasum -a 256 ${PROOF_FILENAME}`,
    `node scripts/verify-proof.ts ${PROOF_FILENAME}`,
    "```",
    "",
    TRUST,
  ];
}

/** REVIVAL.md: facts, snapshot, commits, plan, autopsy, timeline, issue body, proof reference. */
export function buildRevivalMarkdown(input: RevivalKitInput): string {
  const { result, resource } = input;
  const meta = result.github?.meta;
  const sections: string[][] = [
    [
      `# Revival plan: ${meta ? escapeMarkdown(meta.fullName) : escapeMarkdown(resource)}`,
      "",
      `Generated in the browser by Gravekeeper from a verified lookup of ${escapeMarkdown(resource)} recorded at ${recordedAt(result)}. Nothing in this file was fetched again; it repeats the data the proof signs. The plan uses repository metadata and declared dependency versions only. It is not a source code or security audit.`,
    ],
    ...(meta ? [factsSection(result)] : []),
    ["## Archive snapshot", "", `- ${snapshotLine(result)}`],
    ...(meta ? [commitsSection(result)] : []),
    planSection(result),
    ...(result.autopsy ? [autopsySection(result.autopsy)] : []),
    ...(result.timeline ? [timelineSection(result.timeline)] : []),
    [
      "## Revival tracking issue",
      "",
      'Paste everything between the two rules into a new GitHub issue titled "Revival tracking issue".',
      "",
      "---",
      "",
      buildIssueBody(input).trimEnd(),
      "",
      "---",
    ],
    proofSection(input),
  ];
  return sections.map((lines) => lines.join("\n")).join("\n\n") + "\n";
}
